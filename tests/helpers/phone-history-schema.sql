BEGIN;

CREATE SCHEMA IF NOT EXISTS phone_commander;

-- 01. Physical Android devices. ADB endpoint is a transient runtime concern.
-- Hashes should be opaque SHA-256 hex values generated by the backend.
CREATE TABLE IF NOT EXISTS phone_commander.devices (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    serial_hash            TEXT NOT NULL,
    physical_identity_hash TEXT UNIQUE,
    model                  TEXT NOT NULL,
    manufacturer           TEXT,
    android_version        TEXT,
    status                 TEXT NOT NULL DEFAULT 'DISCONNECTED'
                           CHECK (status IN ('CONNECTED','DISCONNECTED','UNAUTHORIZED','OFFLINE','ERROR')),
    first_seen_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metadata               JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(metadata) = 'object'),
    CHECK (serial_hash ~ '^[[:xdigit:]]{64}$'),
    CHECK (physical_identity_hash IS NULL OR physical_identity_hash ~ '^[[:xdigit:]]{64}$'),
    CHECK (last_seen_at >= first_seen_at)
);

-- 02. Installed apps as observed on individual devices.
CREATE TABLE IF NOT EXISTS phone_commander.app_catalog (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id              UUID NOT NULL REFERENCES phone_commander.devices(id),
    package_name           TEXT NOT NULL,
    app_name               TEXT NOT NULL,
    version_code           TEXT,
    version_name           TEXT,
    label_source           TEXT NOT NULL DEFAULT 'ADB',
    last_scanned_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (device_id, package_name),
    CHECK (length(trim(package_name)) > 0),
    CHECK (length(trim(app_name)) > 0)
);

-- 03. Command corpus for analysis/evaluation, NOT an authorization source.
-- Store only command_text that has been redacted and consented to as appropriate.
CREATE TABLE IF NOT EXISTS phone_commander.command_corpus (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    command_text           TEXT,
    command_hash           TEXT,
    language_hint          TEXT,
    decision               TEXT NOT NULL DEFAULT 'UNKNOWN'
                           CHECK (decision IN ('TOOL','CLARIFY','REFUSE','UNSUPPORTED','UNKNOWN')),
    proposed_tool          TEXT,
    proposed_args          JSONB CHECK (proposed_args IS NULL OR jsonb_typeof(proposed_args) = 'object'),
    outcome                TEXT NOT NULL DEFAULT 'UNKNOWN'
                           CHECK (outcome IN ('CORRECT','WRONG','UNKNOWN')),
    source                 TEXT NOT NULL DEFAULT 'REAL_USER'
                           CHECK (source IN ('REAL_USER','DEV','BENCHMARK')),
    resolved_in_version    TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at             TIMESTAMPTZ,
    CHECK (command_text IS NOT NULL OR command_hash IS NOT NULL),
    CHECK (expires_at IS NULL OR expires_at > created_at)
);

-- 04. Skill catalog, scoped to applications, never executable code.
CREATE TABLE IF NOT EXISTS phone_commander.skills (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name                   TEXT NOT NULL,
    description            TEXT,
    owner_ref              TEXT,
    app_scope              JSONB NOT NULL DEFAULT '[]'::jsonb
                           CHECK (jsonb_typeof(app_scope) = 'array'),
    status                 TEXT NOT NULL DEFAULT 'DRAFT'
                           CHECK (status IN ('DRAFT','PENDING_VALIDATION','VERIFIED','DISABLED')),
    current_version_id     UUID,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (length(trim(name)) > 0)
);

-- 05. Declarative workflows. Executor must validate schemas and permissions.
CREATE TABLE IF NOT EXISTS phone_commander.skill_versions (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    skill_id               UUID NOT NULL REFERENCES phone_commander.skills(id),
    version_no             INTEGER NOT NULL CHECK (version_no > 0),
    workflow_json          JSONB NOT NULL CHECK (jsonb_typeof(workflow_json) = 'object'),
    parameter_schema       JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(parameter_schema) = 'object'),
    verification_schema    JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(verification_schema) = 'object'),
    status                 TEXT NOT NULL DEFAULT 'DRAFT'
                           CHECK (status IN ('DRAFT','PENDING_VALIDATION','VERIFIED','DISABLED')),
    schema_version         INTEGER NOT NULL DEFAULT 1 CHECK (schema_version > 0),
    compiler_version       TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (skill_id, version_no),
    UNIQUE (skill_id, id)
);

-- Prevent skills.current_version_id pointing at a version of another skill.
DO $ddl$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conname = 'skills_current_version_belongs_to_skill_fk'
           AND conrelid = 'phone_commander.skills'::regclass
    ) THEN
        ALTER TABLE phone_commander.skills
          ADD CONSTRAINT skills_current_version_belongs_to_skill_fk
          FOREIGN KEY (id, current_version_id)
          REFERENCES phone_commander.skill_versions(skill_id, id)
          DEFERRABLE INITIALLY DEFERRED;
    END IF;
END;
$ddl$;

-- 06. Unified execution records. An execution may use zero or one learned skill.
-- Do not store single-use permissions/grants or make this a replay authority.
CREATE TABLE IF NOT EXISTS phone_commander.executions (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id              UUID NOT NULL REFERENCES phone_commander.devices(id),
    skill_version_id       UUID REFERENCES phone_commander.skill_versions(id),
    command_corpus_id      UUID REFERENCES phone_commander.command_corpus(id),
    original_command       TEXT, -- optional redacted copy, not guaranteed raw user text
    engine                 TEXT NOT NULL
                           CHECK (engine IN ('ACTION_PLAN','GOAL_V1','GOAL_V2','UNIFIED','HYBRID')),
    status                 TEXT NOT NULL DEFAULT 'PLANNED'
                           CHECK (status IN ('PLANNED','QUEUED','RUNNING','WAITING_APPROVAL',
                                            'COMPLETED','BLOCKED','DENIED','CANCELLED',
                                            'FAILED','UNVERIFIED')),
    router_reason          TEXT,
    terminal_reason        TEXT,
    started_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at            TIMESTAMPTZ,
    analyze_ms             INTEGER CHECK (analyze_ms IS NULL OR analyze_ms >= 0),
    execute_ms             INTEGER CHECK (execute_ms IS NULL OR execute_ms >= 0),
    model_calls            INTEGER CHECK (model_calls IS NULL OR model_calls >= 0),
    rpc_count              INTEGER CHECK (rpc_count IS NULL OR rpc_count >= 0),
    adb_count              INTEGER CHECK (adb_count IS NULL OR adb_count >= 0),
    runtime_digest         TEXT,
    UNIQUE (id, device_id),
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

-- 07. Ordered logical steps of an execution.
CREATE TABLE IF NOT EXISTS phone_commander.execution_steps (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    execution_id           UUID NOT NULL REFERENCES phone_commander.executions(id),
    step_order             INTEGER NOT NULL CHECK (step_order > 0),
    label                  TEXT,
    capability             TEXT,
    action_type            TEXT,
    status                 TEXT NOT NULL DEFAULT 'PENDING'
                           CHECK (status IN ('PENDING','RUNNING','VERIFIED','COMPLETED',
                                            'BLOCKED','FAILED','SKIPPED','CANCELLED','UNVERIFIED')),
    evidence_tier          TEXT,
    failure_category       TEXT,
    dispatch_state         TEXT, -- metadata ONLY; journal remains authoritative
    started_at             TIMESTAMPTZ,
    finished_at            TIMESTAMPTZ,
    UNIQUE (execution_id, step_order),
    UNIQUE (execution_id, id),
    CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

-- 08. Metadata and references for evidence stored outside the DB.
CREATE TABLE IF NOT EXISTS phone_commander.evidence_index (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    execution_id           UUID NOT NULL REFERENCES phone_commander.executions(id),
    step_id                UUID,
    evidence_type          TEXT NOT NULL,
    evidence_tier          TEXT,
    content_hash           TEXT,
    storage_ref            TEXT, -- opaque managed reference, NOT arbitrary URL/path
    redacted               BOOLEAN NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at             TIMESTAMPTZ,
    CHECK (expires_at IS NULL OR expires_at > created_at)
);

-- 09. Real model-provider requests. Requested vs actual avoids fallback confusion.
CREATE TABLE IF NOT EXISTS phone_commander.provider_usage (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    execution_id           UUID REFERENCES phone_commander.executions(id),
    requested_provider     TEXT NOT NULL,
    actual_provider        TEXT,
    model                  TEXT,
    request_count          INTEGER NOT NULL DEFAULT 1 CHECK (request_count >= 0),
    prompt_tokens          INTEGER CHECK (prompt_tokens IS NULL OR prompt_tokens >= 0),
    completion_tokens      INTEGER CHECK (completion_tokens IS NULL OR completion_tokens >= 0),
    latency_ms             INTEGER CHECK (latency_ms IS NULL OR latency_ms >= 0),
    http_status            SMALLINT CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    retry_after_ms         INTEGER CHECK (retry_after_ms IS NULL OR retry_after_ms >= 0),
    fallback_reason        TEXT,
    recorded_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. A demonstration session on exactly one device at a time.
CREATE TABLE IF NOT EXISTS phone_commander.teach_sessions (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    skill_id               UUID REFERENCES phone_commander.skills(id),
    device_id              UUID NOT NULL REFERENCES phone_commander.devices(id),
    original_command       TEXT, -- redacted; never passwords/OTP
    status                 TEXT NOT NULL DEFAULT 'RECORDING'
                           CHECK (status IN ('RECORDING','PAUSED','COMPLETED','CANCELLED','FAILED')),
    started_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at            TIMESTAMPTZ,
    UNIQUE (id, device_id),
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

-- 11. UI snapshots; persist sanitized metadata and storage references only.
CREATE TABLE IF NOT EXISTS phone_commander.ui_snapshots (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    teach_session_id       UUID NOT NULL REFERENCES phone_commander.teach_sessions(id),
    device_id              UUID NOT NULL REFERENCES phone_commander.devices(id),
    app_package            TEXT,
    activity               TEXT,
    ui_metadata_ref        TEXT,  -- sanitized XML snapshot reference, optional
    screenshot_ref         TEXT,  -- opt-in, redacted screenshot reference, optional
    content_hash           TEXT,
    ui_semantics           JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(ui_semantics) = 'object'),
    captured_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at             TIMESTAMPTZ,
    UNIQUE (teach_session_id, id),
    CHECK (expires_at IS NULL OR expires_at > captured_at)
);

-- 12. Recorded interactions. No coordinate-only replay selectors.
CREATE TABLE IF NOT EXISTS phone_commander.recorded_actions (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id             UUID NOT NULL REFERENCES phone_commander.teach_sessions(id),
    step_order             INTEGER NOT NULL CHECK (step_order > 0),
    action_type            TEXT NOT NULL,
    semantic_target        JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(semantic_target) = 'object'),
    input_template         TEXT, -- e.g. {{search_query}}, NEVER password/OTP
    before_snapshot_id     UUID,
    after_snapshot_id      UUID,
    recorded_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (session_id, step_order)
);

-- 13. Validation runs, separately scoped to each device and app version.
CREATE TABLE IF NOT EXISTS phone_commander.skill_tests (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    skill_version_id       UUID NOT NULL REFERENCES phone_commander.skill_versions(id),
    device_id              UUID NOT NULL REFERENCES phone_commander.devices(id),
    execution_id           UUID REFERENCES phone_commander.executions(id),
    app_package            TEXT,
    app_version            TEXT,
    test_kind              TEXT NOT NULL DEFAULT 'OFFLINE'
                           CHECK (test_kind IN ('OFFLINE','REAL_ANDROID')),
    result                 TEXT NOT NULL DEFAULT 'UNVERIFIED'
                           CHECK (result IN ('PASS','FAIL','BLOCKED','UNVERIFIED')),
    evidence_ref           TEXT,
    verifier_name          TEXT,
    tested_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 14. Security audit events; NO approval tokens, grants or owner-scope secrets.
CREATE TABLE IF NOT EXISTS phone_commander.audit_events (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id              UUID REFERENCES phone_commander.devices(id),
    execution_id           UUID REFERENCES phone_commander.executions(id),
    actor_ref              TEXT,
    event_type             TEXT NOT NULL,
    mode                   TEXT,
    decision               TEXT CHECK (decision IS NULL OR decision IN ('ALLOW','ASK','DENY')),
    reason                 TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 15. User-facing consent history. This is NOT an execution/grant authority.
-- subject_ref must come from authenticated identity; no global default consent.
CREATE TABLE IF NOT EXISTS phone_commander.consents (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_ref            TEXT NOT NULL,
    device_id              UUID REFERENCES phone_commander.devices(id),
    consent_type           TEXT NOT NULL
                           CHECK (consent_type IN ('CLOUD_COMMAND_TEXT','CLOUD_IMAGE','TEACH_RECORDING')),
    granted                BOOLEAN NOT NULL,
    scope                  JSONB NOT NULL DEFAULT '{}'::jsonb
                           CHECK (jsonb_typeof(scope) = 'object'),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at             TIMESTAMPTZ,
    revoked_at             TIMESTAMPTZ,
    CHECK (length(trim(subject_ref)) > 0),
    CHECK (expires_at IS NULL OR expires_at > created_at),
    CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

-- Composite foreign keys added after all tables exist.
-- These constraints prevent associating evidence, snapshots, or tests with
-- steps/devices belonging to a different execution/session.
-- Named constraints + presence checks make reruns safe on an already-created schema.
DO $ddl$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'phone_commander.evidence_index'::regclass
           AND conname = 'evidence_step_same_execution_fk'
    ) THEN
        ALTER TABLE phone_commander.evidence_index
            ADD CONSTRAINT evidence_step_same_execution_fk
            FOREIGN KEY (execution_id, step_id)
            REFERENCES phone_commander.execution_steps(execution_id, id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'phone_commander.ui_snapshots'::regclass
           AND conname = 'snapshot_same_device_as_session_fk'
    ) THEN
        ALTER TABLE phone_commander.ui_snapshots
            ADD CONSTRAINT snapshot_same_device_as_session_fk
            FOREIGN KEY (teach_session_id, device_id)
            REFERENCES phone_commander.teach_sessions(id, device_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'phone_commander.recorded_actions'::regclass
           AND conname = 'recorded_before_snapshot_same_session_fk'
    ) THEN
        ALTER TABLE phone_commander.recorded_actions
            ADD CONSTRAINT recorded_before_snapshot_same_session_fk
            FOREIGN KEY (session_id, before_snapshot_id)
            REFERENCES phone_commander.ui_snapshots(teach_session_id, id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'phone_commander.recorded_actions'::regclass
           AND conname = 'recorded_after_snapshot_same_session_fk'
    ) THEN
        ALTER TABLE phone_commander.recorded_actions
            ADD CONSTRAINT recorded_after_snapshot_same_session_fk
            FOREIGN KEY (session_id, after_snapshot_id)
            REFERENCES phone_commander.ui_snapshots(teach_session_id, id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'phone_commander.skill_tests'::regclass
           AND conname = 'skill_test_execution_same_device_fk'
    ) THEN
        ALTER TABLE phone_commander.skill_tests
            ADD CONSTRAINT skill_test_execution_same_device_fk
            FOREIGN KEY (execution_id, device_id)
            REFERENCES phone_commander.executions(id, device_id);
    END IF;
END;
$ddl$;

-- Indexes for device lookups, execution reports and compatibility checks.
CREATE INDEX IF NOT EXISTS idx_devices_last_seen
    ON phone_commander.devices(last_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_devices_serial_hash
    ON phone_commander.devices(serial_hash);
CREATE INDEX IF NOT EXISTS idx_app_catalog_device
    ON phone_commander.app_catalog(device_id, last_scanned_at DESC);
CREATE INDEX IF NOT EXISTS idx_corpus_failure_time
    ON phone_commander.command_corpus(outcome, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_corpus_expiry
    ON phone_commander.command_corpus(expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_skills_status
    ON phone_commander.skills(status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_skill_versions_skill
    ON phone_commander.skill_versions(skill_id, version_no DESC);
CREATE INDEX IF NOT EXISTS idx_executions_device_time
    ON phone_commander.executions(device_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_executions_status_time
    ON phone_commander.executions(status, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_executions_skill_version
    ON phone_commander.executions(skill_version_id) WHERE skill_version_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_execution_steps_execution
    ON phone_commander.execution_steps(execution_id, step_order);
CREATE INDEX IF NOT EXISTS idx_evidence_execution
    ON phone_commander.evidence_index(execution_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_evidence_expiry
    ON phone_commander.evidence_index(expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_provider_usage_time
    ON phone_commander.provider_usage(recorded_at DESC, actual_provider);
CREATE INDEX IF NOT EXISTS idx_provider_usage_execution
    ON phone_commander.provider_usage(execution_id) WHERE execution_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_teach_sessions_skill
    ON phone_commander.teach_sessions(skill_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_teach_sessions_device
    ON phone_commander.teach_sessions(device_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_ui_snapshots_session
    ON phone_commander.ui_snapshots(teach_session_id, captured_at);
CREATE INDEX IF NOT EXISTS idx_ui_snapshots_device
    ON phone_commander.ui_snapshots(device_id, captured_at DESC);
CREATE INDEX IF NOT EXISTS idx_ui_snapshots_expiry
    ON phone_commander.ui_snapshots(expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_recorded_actions_session
    ON phone_commander.recorded_actions(session_id, step_order);
CREATE INDEX IF NOT EXISTS idx_skill_tests_compatibility
    ON phone_commander.skill_tests(skill_version_id, device_id, app_package, app_version, tested_at DESC);
CREATE INDEX IF NOT EXISTS idx_skill_tests_execution
    ON phone_commander.skill_tests(execution_id) WHERE execution_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_audit_events_time
    ON phone_commander.audit_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_device
    ON phone_commander.audit_events(device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_consents_subject_kind
    ON phone_commander.consents(subject_ref, consent_type, created_at DESC);

COMMENT ON SCHEMA phone_commander IS
    'Phone Commander unified device, execution, learning and audit data';
COMMENT ON TABLE phone_commander.executions IS
    'Analytics/history only. Effect journal is source of truth for dispatch and replay safety.';
COMMENT ON TABLE phone_commander.skill_versions IS
    'Declarative workflows only; backend validates every action/permission/verifier.';
COMMENT ON TABLE phone_commander.consents IS
    'Consent history; does not grant reusable execution authorization.';
COMMENT ON COLUMN phone_commander.recorded_actions.semantic_target IS
    'Semantic UI evidence, not a raw screen coordinate replay selector.';

COMMIT;

